#pragma once

#include <cstddef>
#include <cstdint>

// Адресное пространство процесса игры. Игра 32-битная (LAA — до 4 ГБ), и "out of memory" у неё почти всегда
// значит, что кончилось АДРЕСНОЕ ПРОСТРАНСТВО (или в нём не осталось непрерывного куска), а не оперативная память.
// Диспетчер задач показывает рабочий набор — это совсем другое число, поэтому здесь считаем по-своему:
// обходим карту виртуальной памяти (VirtualQuery) и раскладываем по типам.
namespace MemMap
{
    struct Stats
    {
        uint64_t limit = 0;            // верх адресного пространства для приложения (4 ГБ у LAA на 64-битной Windows)
        uint64_t committedPrivate = 0; // куча игры, драйвер, стеки
        uint64_t committedImage = 0;   // exe и DLL (libcef.dll, драйвер видеокарты, ...)
        uint64_t committedMapped = 0;  // отображённые файлы и секции
        uint64_t reserved = 0;         // зарезервировано, но не выделено
        uint64_t free = 0;             // свободно
        uint64_t largestFree = 0;      // самый большой непрерывный свободный кусок
    };

    Stats Take();

    // Одна строка для отчёта. Не выделяет память из кучи — вызывается и из обработчика сбоев, когда её может не быть.
    void Summary(char* buf, size_t size);

    // В консоль: сводка, минимум запаса за сессию и самые большие модули (по размеру образа).
    void Print();

    // Из главного цикла: раз в ~10 с смотрит запас; мало — предупреждение в лог (не чаще раза в минуту).
    void Poll();
}
