#pragma once

#include <string>

// Сверка модов в сетевой комнате.
//
// Хост раз в секунду смотрит, кто подключён к комнате, и спрашивает каждого нового про моды
// (наш сетевой пакет). Клиент с модлоадером отвечает отпечатком своих модов. Не совпал —
// хост выгоняет игрока (LanKillClient) и сообщает ему причину; не ответил за kAnswerMs —
// значит, у него чистая игра без модлоадера, тоже выгоняет.
//
// В отпечаток входят только моды, которые влияют на партию: multiplayer = "required" и есть
// серверная или shared-часть. Клиентские (интерфейс, графика, инструменты) не учитываются —
// их у игроков может быть разный набор.
namespace ModCheck
{
    constexpr char kModId[] = "__modloader"; // "мод" для служебных пакетов модлоадера

    void Install();

    // Служебный пакет (mod == kModId) из Net. Главный поток игры.
    void OnMessage(char direction, const std::string& event, const std::string& data, int from);

    void Print(); // .modcheck — отпечаток и что в него входит
}
