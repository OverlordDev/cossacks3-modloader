#pragma once

#include <string>

// Веб-интерфейс поверх игры: страница HTML/CSS/JS рисуется браузером в текстуру, текстура выводится
// в том же хуке SwapBuffers, где живёт меню модлоадера.
//
// CEF лежит отдельной папкой <игра>/cef и подключается по требованию: нет папки — модлоадер работает
// как раньше, просто без веб-интерфейса. Браузер стартует не при загрузке, а когда его впервые
// попросят (.web <url>), поэтому обычная работа и перезагрузка сборки ничем не рискуют.
//
// Всё, кроме Available() и Request*(), исполняется в потоке рендера игры.
namespace WebUi
{
    bool Available();     // есть <игра>/cef/libcef.dll и Cossacks3Cef.exe
    bool Running();       // CEF поднят
    bool IsOpen();        // страница открыта
    std::string Status(); // строка для консоли

    // Из потока модлоадера: отложенные команды, выполняются в потоке рендера.
    // Принимает адрес (со схемой), путь к файлу или имя страницы в modloader/web.
    void RequestOpen(const std::string& url);
    // Выполнить код в открытой странице.
    void RequestEval(const std::string& javascript);
    void RequestClose();
    void RequestReload();

    // Из хука SwapBuffers: команды и насос сообщений CEF. OpenGL не трогает.
    void OnFrame(HWND window);

    // Есть готовый кадр браузера — его нужно нарисовать.
    bool HasFrame();

    // Игра пересоздала контекст OpenGL (так бывает при загрузке партии): старые текстуры
    // пропали вместе с ним. Забыть их номера — на следующем кадре создадутся заново.
    void OnContextLost();

    // Залить кадр в текстуру и вернуть её номер (0 — нечего рисовать). Вызывать только там, где
    // состояние OpenGL уже приведено в порядок, то есть из кадра ImGui в Overlay.
    unsigned int Present(int* width, int* height);

    // Слой выпадающего списка <select>: рисуется поверх страницы в указанном месте.
    // 0 — списка сейчас нет.
    unsigned int PresentPopup(int* x, int* y, int* width, int* height);

    // Режим HUD (интерфейс поверх партии): мышь над прозрачным местом страницы уходит в игру,
    // над нарисованным — странице; клавиатура — игре, пока на странице не активно поле ввода.
    // Выключен — страница забирает весь ввод (меню). Сбрасывается при закрытии страницы.
    void SetPassthrough(bool on);
    bool Passthrough();

    // Адрес открытой страницы ("" — ничего не открыто).
    std::string CurrentUrl();

    // Из оконной процедуры. true — сообщение съедено, игре его отдавать не надо.
    bool OnWndProc(HWND window, UINT msg, WPARAM wp, LPARAM lp);

    // Из потока модлоадера перед выгрузкой DLL.
    void Shutdown();
}
