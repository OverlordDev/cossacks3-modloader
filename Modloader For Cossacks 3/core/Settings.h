// Настройки модлоадера: <игра>\modloader\settings.txt, по строке на ключ:
//   render = 0        не трогать отрисовку вообще (ни меню по Insert, ни счётчик кадров)
//   assets = 0        не подменять файлы игры файлами модов
//   checksum = 0      не подменять контрольную сумму скриптов для лобби
//   console = 0       не открывать окно консоли
// Значения: 0/false/no — выключено, всё остальное — включено. Файла нет — всё включено.
//
// Нужно, чтобы на чужой машине можно было отключить подозрительную часть, не пересобирая DLL.
namespace Settings
{
    bool Enabled(const char* key, bool byDefault = true);
}
