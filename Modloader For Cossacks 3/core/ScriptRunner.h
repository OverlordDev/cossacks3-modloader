#pragma once

#include <functional>

// Выполнение произвольного кода игрового скрипта (DWScript) из модлоадера.
// Код ставится в очередь из любого потока и исполняется в главном потоке игры (там же работают скрипты).
namespace ScriptRunner
{
    void Install();
    void Update();    // из цикла модлоадера: цепляется к главному окну игры, когда оно появится
    void Uninstall(); // до выгрузки DLL: возвращает оконную процедуру
    DWORD GameThreadId(); // главный поток игры (0, пока окно не найдено)

    // Каждая строка — одна строка скрипта, как в .inc-файлах игры.
    void Queue(std::vector<std::string> lines);

    // C++-код в главном потоке игры (для работы с объектами движка).
    void RunOnGameThread(std::function<void()> fn);
    bool IsGameThread();

    // Синхронно, только из главного потока игры. Код (ANSI, строки через \n) компилируется один раз
    // и кэшируется; меняющиеся данные передавайте через arg. В коде доступны макросы:
    //   ML_ARG        — строка-аргумент (arg)
    //   ML_RET(expr)  — вернуть строковое значение в *result
    // false — ошибка компиляции/исключение (подробности в логе).
    bool Call(const std::string& code, const std::string& arg, std::string* result);
}
