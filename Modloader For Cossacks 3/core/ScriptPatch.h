#pragma once

#include <string>

// Патчи скриптов игры (data/scripts/lib/*.script и любых других текстовых файлов) при загрузке.
//
// Мод кладёт файл patches/<путь в игре>.patch, например
//   modloader/mods/<мод>/patches/data/scripts/lib/unit.script.patch
// и движок получит unit.script уже с правками. Файлы игры не меняются. Несколько модов могут
// править один файл — патчи применяются по очереди (моды по алфавиту папок).
//
// Формат патча — блоки, каждый начинается строкой-командой с @ в начале строки:
//
//   @replace _unit_OrderMove        -- заменить функцию/процедуру целиком (от объявления до end;)
//   function _unit_OrderMove(...) : Pointer;
//   begin
//      ...
//   end;
//
//   @begin _unit_AddOrder           -- вставить строки сразу после begin функции
//   if itype = gc_obj_order_type_move then Log('move');
//
//   @end _unit_AddOrder             -- вставить строки перед последним end; функции
//   @before _unit_AddOrder          -- вставить строки перед объявлением функции (новые функции)
//   @after _unit_AddOrder           -- вставить строки после её end;
//   @append                         -- в конец файла
//
//   @find                           -- найти текст (одна или несколько строк, точно)...
//   Result := nil;
//   @with                           -- ...и заменить (все вхождения в файле)
//   Result := nil; Log('x');
//
// Строки, начинающиеся с "@@", — комментарии. Кодировка патча — UTF-8 или ANSI (как у игры).
// Имя функции ищется без учёта регистра по объявлению в начале строки: "function Имя" / "procedure Имя".
namespace ScriptPatch
{
    // Применить патч к тексту файла. who — для сообщений ("мод/путь"). Вернёт число применённых блоков;
    // ошибки (нет функции, нет текста) пишутся в лог, блок пропускается.
    int Apply(std::string& text, const std::string& patch, const std::string& who);

    // Встроенные правки модлоадера для файла (key — "data\scripts\lib\unit.script"); пусто — нет.
    // Каждая вставка — отдельная строка с 'ML:', поэтому контрольная сумма лобби их не видит.
    std::string Builtin(const std::string& key);
}
