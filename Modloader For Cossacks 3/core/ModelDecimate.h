#pragma once

#include <string>

// Упрощение скелетных моделей игры (.oss): меньше треугольников -> дешевле толпа юнитов.
//
// В .oss скиннинг лежит отдельно от вершин (кадры — готовые матрицы костей, MODEL_FORMATS.md §2),
// поэтому вершины и треугольники можно убирать, не трогая анимацию. Остаются нетронутыми: кадры,
// число костей, веса и позиции оставшихся вершин.
namespace ModelDecimate
{
    struct Stats { int vertsBefore = 0, vertsAfter = 0, trisBefore = 0, trisAfter = 0; };

    // ratio — доля треугольников, которую оставить (0.1..1). Схлопывание рёбер по квадрикам (QEM):
    //  - вершина остаётся на месте одной из двух вершин ребра, её кость и UV не смешиваются;
    //  - ребро между разными костями (сустав) дороже — иначе при анимации сустав рвётся;
    //  - края открытой сетки и складки UV не двигаются, лишь бы не портить силуэт;
    //  - схлопывание, переворачивающее соседний треугольник, запрещено.
    // Модель, где меньше kMinTriangles треугольников, возвращается как есть.
    // Алгоритм не поймёт, что сделал что-то плохое с внешним видом: смотреть глазами, в игре.
    bool DecimateOss(const std::string& oss, float ratio, std::string* out, Stats* stats, std::string* error);

    constexpr int kMinTriangles = 40;
}
