#pragma once

#include <string>

// Режим экономии памяти: срезать верхние мип-уровни у больших текстур игры.
//
// Текстуры игры — DDS DXT1/3/5 уже с готовой цепочкой мипов (MODEL_FORMATS.md §6). Убрать верхний уровень —
// значит выкинуть первый блок данных и поправить заголовок (размер, число мипов): пережимать ничего не надо,
// оставшиеся уровни байт-в-байт те же. Каждый срезанный уровень — минус 3/4 памяти этой текстуры.
namespace TextureShrink
{
    enum class Result
    {
        Shrunk,      // out заполнен, dropped — сколько уровней убрано
        Unchanged,   // и так не больше maxSide (или нечего срезать)
        Unsupported, // не DDS / не DXT1,3,5 / кубическая или объёмная / оборванный файл — оставить как есть
    };

    // Большая сторона текстуры по 128-байтному заголовку (false — не DDS): чтобы не читать файл целиком зря.
    bool TopSide(const std::string& head, unsigned* side);

    // maxSide — максимальная сторона (пиксели), режем, пока большая сторона больше неё. Мипов остаётся минимум один.
    Result Shrink(const std::string& dds, unsigned maxSide, std::string* out, int* dropped);
}
