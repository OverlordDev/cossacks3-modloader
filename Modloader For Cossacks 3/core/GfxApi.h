#pragma once

// Графика для Lua: таблица gfx в клиентском окружении (и в консоли).
//
// Графика — дело каждого компьютера: меняет только картинку у того, кто её включил, и не влияет
// на ход партии. Поэтому нативы графики разрешены клиентским скриптам, хотя это и Set*.
// Список разрешённых — kGfxNatives ниже: только то, что рисует, ничего из игровой логики.
namespace GfxApi
{
    // Разрешён ли натив клиентским скриптам как gfx.<Name>.
    bool IsGraphicsNative(const char* name);

    // Удобные обёртки поверх gfx.<Name> (gfx.fog{...}, gfx.shadows{...} и т.д.) — грузятся в базовое
    // окружение клиента после создания таблицы gfx.
    const char* Prelude();
}
